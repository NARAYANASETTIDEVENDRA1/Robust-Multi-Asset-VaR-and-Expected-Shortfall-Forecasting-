def es_unconditional_test(X_obs, VaR, ES, alpha=0.05, nSim=10000, rng=None):




    X_obs = np.asarray(X_obs)
    VaR = np.asarray(VaR)
    ES = np.asarray(ES)
    T = len(X_obs)

    if rng is None:
        rng = np.random.default_rng(GLOBAL_SEED)

    # -------------------------------------------------
    # 1. Convert RETURNS -> LOSSES
    # -------------------------------------------------
    L = -X_obs
    VaR_L = -VaR
    ES_L = -ES

    # -------------------------------------------------
    # 2. Observed test statistic
    # -------------------------------------------------
    I = (L >= VaR_L).astype(float)

    stat = (1 / (T * alpha)) * np.sum((L * I) / ES_L) - 1

    # -------------------------------------------------
    # 3. Simulate null distribution
    # -------------------------------------------------
    sim_stats = np.zeros(nSim)

    for b in range(nSim):

        U = rng.uniform(size=T)
        Z = rng.exponential(scale=1.0, size=T)

        I_sim = (U < alpha).astype(float)

        # Under null:
        # Tail losses = ES_L * Exp(1)
        L_sim = np.where(
            I_sim == 1,
            ES_L * Z,
            0.0
        )

        sim_stats[b] = (1 / (T * alpha)) * np.sum((L_sim * I_sim) / ES_L) - 1

    # -------------------------------------------------
    # 4. p-value (left tail test)
    # -------------------------------------------------
    p_value = np.mean(sim_stats <= stat)
    crit_val = np.percentile(sim_stats, 100 * alpha)

    return stat, crit_val, p_value


