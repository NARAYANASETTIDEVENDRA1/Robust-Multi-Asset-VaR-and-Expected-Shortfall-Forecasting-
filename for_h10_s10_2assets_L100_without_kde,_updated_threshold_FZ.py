def empirical_pairwise_lambda_avg(U, q=0.05):
    if U.ndim == 3 and U.shape[1] == 1:
        U = U[:, 0, :]   # (n_paths, d)

    n, d = U.shape
    pairs = list(combinations(range(d), 2))
    vals = []

    for i, j in pairs:
        joint = np.sum((U[:, i] < q) & (U[:, j] < q))
        vals.append(joint / (n * q))

    return np.mean(vals), vals, pairs


