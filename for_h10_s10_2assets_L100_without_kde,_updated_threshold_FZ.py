def kupiec_lr_test(violations, alpha):
    """
    Kupiec (1995) Unconditional Coverage Test (LR_UC)
    """
    violations = np.asarray(violations, dtype=int)
    n = len(violations)
    x = violations.sum()

    # Degenerate cases
    if x == 0 or x == n:
        return np.nan, np.nan

    phat = x / n

    logL0 = (n - x) * np.log(1 - alpha) + x * np.log(alpha)
    logL1 = (n - x) * np.log(1 - phat) + x * np.log(phat)

    LR_uc = -2 * (logL0 - logL1)
    p_value = 1 - chi2.cdf(LR_uc, df=1)

    return LR_uc, p_value

def fz_score(y, var, es, alpha):
    """
    Fissler–Ziegel (2016) joint VaR–ES scoring rule (FZ0)
    Lower is better.
    """
    y = np.asarray(y)
    var = np.asarray(var)
    es = np.asarray(es)

    eps = 1e-12
    es_safe = np.minimum(es, -eps)

    I = (y <= var).astype(float)

    term1 = -(1.0 / (alpha * es_safe)) * I * (var - y)
    term2 = var / es_safe
    term3 = np.log(-es_safe) - 1.0

    return term1 + term2 + term3
