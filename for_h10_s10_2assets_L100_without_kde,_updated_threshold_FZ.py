def simulate_portfolio_var_es_horizon(
    vine_model,
    inverse_cdf_funcs,
    mu0_map,
    sigma0_map,
    garch_params_map,
    weights,
    n_paths=10000,
    horizon=10,
    alpha=0.05,
    window_seed=42,
    q_lambda=0.05

):
    """
    Full pathwise Monte Carlo for h-day VaR / ES
    PLUS correct copula-based lambda_hat for model selection
    """

    stocks = list(mu0_map.keys())
    d = len(stocks)

    # =====================================================
    # (A) ---- LAMBDA HAT (COPULA-ONLY, HORIZON-FREE) ----
    # =====================================================


    # =====================================================
    # (B) ---- HORIZON h PATHWISE SIMULATION ----
    # =====================================================
    port_paths = np.zeros((n_paths, horizon))

    mu_paths = {s: np.full(n_paths, mu0_map[s]) for s in stocks}
    sigma_paths = {s: np.full(n_paths, sigma0_map[s]) for s in stocks}


    for h in range(horizon):

        # ---- 1) simulate copula uniforms (risk only) ----
        U = vine_model.simulate(n_paths, seeds=[window_seed+h])
        if h==0:

          lam_hat, _, _ = empirical_pairwise_lambda_avg(U, q=q_lambda)

        # ---- 2) uniforms → residuals ----
        Z = np.zeros_like(U)
        for j, s in enumerate(stocks):
            Z[:, j] = inverse_cdf_funcs[s](U[:, j])

        # ---- 3) returns + GARCH update ----
        daily_returns = np.zeros((n_paths, d))

        for j, s in enumerate(stocks):

            mu = mu_paths[s]
            sigma = sigma_paths[s]
            eps = Z[:, j]

            r = mu + sigma * eps
            k=sigma*eps
            daily_returns[:, j] = r

            p = garch_params_map[s]
            omega, alpha_g, beta, gamma = (
                p["omega"], p["alpha"], p["beta"], p["gamma"]
            )

            indicator = (k < 0).astype(float)
            sigma2_next = (
                omega
                + alpha_g * k**2
                + beta * sigma**2
                + gamma * indicator * k**2
            )

            sigma_paths[s] = np.sqrt(np.maximum(sigma2_next, 1e-10))

            mu_paths[s] = p["const"] + p["phi"] * r

        # ---- 4) portfolio aggregation ----
        port_paths[:, h] = daily_returns @ weights

    # =====================================================
    # (C) ---- HORIZON h VaR / ES ----
    # =====================================================
    port_h = port_paths.sum(axis=1)

    VaR_h = np.quantile(port_h, alpha)
    ES_h  = port_h[port_h <= VaR_h].mean()

    # ✅ SAME FORMAT AS YOUR PIPELINE
    return np.array([VaR_h]), np.array([ES_h]), port_paths, lam_hat

