def simulate_portfolio_var_es_horizon_gaussian(
    vine_model,
    mu0_map,
    sigma0_map,
    garch_params_map,
    weights,
    n_paths=10000,
    horizon=10,
    alpha=0.05,
    window_seed=42
):
    """
    Gaussian baseline:
    - Same vine dependence
    - Gaussian residuals
    - Plain GARCH(1,1) recursion (NO GJR)
    - Horizon-h cumulative VaR / ES
    """

    stocks = list(mu0_map.keys())
    d = len(stocks)

    # =====================================================
    # (A) ---- STORAGE ----
    # =====================================================
    port_paths = np.zeros((n_paths, horizon))

    mu_paths    = {s: np.full(n_paths, mu0_map[s]) for s in stocks}
    sigma_paths = {s: np.full(n_paths, sigma0_map[s]) for s in stocks}
    eps_last    = {s: np.zeros(n_paths) for s in stocks}

    # =====================================================
    # (B) ---- PATHWISE SIMULATION ----
    # =====================================================
    for h in range(horizon):

        # 1) simulate copula uniforms
        U = vine_model.simulate(n_paths, seeds=[window_seed + h])

        # lambda_hat (copula-only, computed once)


        # 2) uniforms → Gaussian residuals
        Z = norm.ppf(np.clip(U, 1e-10, 1 - 1e-10))

        daily_returns = np.zeros((n_paths, d))

        # 3) returns + GARCH recursion
        for j, s in enumerate(stocks):

            mu    = mu_paths[s]
            sigma = sigma_paths[s]
            eps   = Z[:, j]

            r = mu + sigma * eps
            daily_returns[:, j] = r
            k=sigma*eps

            # GARCH(1,1) update
            p = garch_params_map[s]
            omega = p["omega"]
            alpha_g = p["alpha"]
            beta = p["beta"]
            gamma = p["gamma"]

            indicator = (k < 0).astype(float)

            sigma2_next = (
                omega
                + alpha_g * k**2
                + beta  * sigma**2
                + gamma * indicator * k**2
                )

            sigma_paths[s] = np.sqrt(np.maximum(sigma2_next, 1e-10))

            mu_paths[s] = p["const"] + p["phi"] * r

        # 4) portfolio aggregation
        port_paths[:, h] = daily_returns @ weights

    # =====================================================
    # (C) ---- HORIZON-h VaR / ES ----
    # =====================================================
    port_h = port_paths.sum(axis=1)

    VaR_h = np.quantile(port_h, alpha)
    ES_h  = port_h[port_h <= VaR_h].mean()

    return np.array([VaR_h]), np.array([ES_h]), port_paths



