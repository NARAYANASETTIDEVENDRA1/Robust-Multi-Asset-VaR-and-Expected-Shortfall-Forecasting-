def fit_garch_gaussian(returns):

    amm = arch_model(
        returns,
        vol="GARCH",
        p=1, o=1, q=1,          # ✅ GJR-GARCH
        dist="normal",
        mean="ARX",
        lags=1,
        rescale=False
    )
    ress = amm.fit(disp="off")

    params = ress.params

    # ---- AR(1) mean ----
    ar_param = [k for k in params.index if k.endswith("[1]")][0]
    phi_1 = params[ar_param]
    const_mu = params["Const"]

    r_t = returns.iloc[-1]
    muu = const_mu + phi_1 * r_t   # μ_{t+1}

    # ---- standardized residuals ----
    sigma_tt = ress.conditional_volatility
    zz = ress.resid / sigma_tt

    # ---- one-step volatility forecast ----
    forecastt = ress.forecast(horizon=1)
    sigma_forecast = np.sqrt(forecastt.variance.values[-1, 0])

    # ---- GJR parameters for horizon simulation ----
    garch_params = {
        "omega": params["omega"],
        "alpha": params["alpha[1]"],
        "beta":  params["beta[1]"],
        "gamma": params.get("gamma[1]", 0.0),   # ✅ leverage
        "phi":   phi_1,
        "const": const_mu
    }

    return muu, sigma_tt, zz, ress, sigma_forecast, garch_params

